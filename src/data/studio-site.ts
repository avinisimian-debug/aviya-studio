export const OTHER_NEED = {
  value: "other",
  label: "עוד לא בטוח / משהו אחר",
} as const;

export function serviceBySlug(slug: string) {
  return SERVICES.find((service) => service.slug === slug) ?? null;
}

export const BUDGET_OPTIONS = [
  { value: "unspecified", label: "לא מציינים כרגע" },
  { value: "open", label: "עוד לא סגור" },
  { value: "to-8", label: "עד ₪8,000" },
  { value: "8-18", label: "₪8,000–₪18,000" },
  { value: "18-plus", label: "₪18,000 ומעלה" },
] as const;

export function budgetLabel(value: string): string {
  return BUDGET_OPTIONS.find((option) => option.value === value)?.label ?? "לא צוין";
}

export function needLabel(value: string): string {
  if (value === OTHER_NEED.value) return OTHER_NEED.label;
  return serviceBySlug(value)?.title ?? value;
}

